def generate_deterministic_synthetic_questions(
    req: QuestionGenerationRequest,
) -> List[QuestionDraft]:
    """
    Deterministic test-only fake generator.
    Labeled explicitly with is_synthetic=True so it can NEVER be promoted to question bank.
    """
    questions: List[QuestionDraft] = []
    bloom_levels = req.target_bloom_levels or ["UNDERSTAND", "APPLY"]

    for idx in range(min(req.num_questions, len(req.chunks) * 2)):
        chunk = req.chunks[idx % len(req.chunks)]
        bloom = bloom_levels[idx % len(bloom_levels)]
        q_id = f"q-syn-{uuid.uuid4().hex[:8]}"

        excerpt = chunk.text[:120].strip()
        question = QuestionDraft(
            id=q_id,
            question_text=f"Regarding '{chunk.title}': What is the primary characteristic of: '{excerpt}...'?",
            question_type="single_choice",
            options=[
                f"A. Core principle defined in {chunk.title}",
                "B. Contradictory opposing claim",
                "C. Extraneous concept not in syllabus",
                "D. None of the above",
            ],
            suggested_answer="A",
            marks=2.0 if bloom in ("ANALYZE", "EVALUATE", "CREATE") else 1.0,
            difficulty="hard" if bloom in ("ANALYZE", "EVALUATE") else "medium",
            bloom_level=bloom,
            bloom_verification_status="UNVERIFIED_BY_LECTURER",
            source_locator=f"chunk:{chunk.chunk_id} - page {chunk.page_number or 1}",
            source_excerpt=excerpt,
            provenance_chunk_id=chunk.chunk_id,
            status="DRAFT",
            is_synthetic=True,
            co_id=req.target_co_id,
            topic_id=req.target_topic_ids[0] if req.target_topic_ids else None,
            validation_warnings=["TEST_ONLY: Generated by deterministic synthetic provider"],
        )
        questions.append(question)

    return questions


@app.post(
    "/api/v1/generate-questions",
    response_model=QuestionGenerationResponse,
    dependencies=[Depends(verify_internal_auth)],
)
async def generate_questions(req: QuestionGenerationRequest):
    """
    Tenant-scoped question generation route.
    Grounded in passed syllabus chunks, preserving provenance and bloom targets.
    """
    if not req.tenant_id or not req.course_offering_id or not req.syllabus_version_id:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="tenant_id, course_offering_id, and syllabus_version_id are mandatory",
        )

    errors: List[str] = []
    chunk_id_map = {c.chunk_id: c for c in req.chunks}

    # In test environment with fake provider flag:
    use_fake = os.getenv("USE_FAKE_LLM_PROVIDER", "false").lower() in ("true", "1", "yes")
    has_real_key = bool(os.getenv("GPUSTACK_API_KEY") or os.getenv("OPENAI_API_KEY"))

    if is_test_environment() and (use_fake or not has_real_key):
        questions = generate_deterministic_synthetic_questions(req)
        return QuestionGenerationResponse(
            tenant_id=req.tenant_id,
            course_offering_id=req.course_offering_id,
            syllabus_version_id=req.syllabus_version_id,
            questions=questions,
            errors=errors,
            provider_info="synthetic-test-provider (is_synthetic=True)",
        )

    if not has_real_key:
        # Production mode without real credentials must fail closed
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail="LLM_PROVIDER_NOT_CONFIGURED: Production LLM credentials (GPUSTACK_API_KEY or OPENAI_API_KEY) are not configured.",
        )

    # In production with verified credentials, invoke vendor logic safely
    try:
        import main as vendor_main

        chunk_dicts = [
            {"index": i, "title": c.title, "text": c.text, "chunk_id": c.chunk_id}
            for i, c in enumerate(req.chunks)
        ]
        vendor_pairs, vendor_errors = vendor_main.call_deepseek_ga_for_chunks(
            chunk_dicts,
            total_questions=req.num_questions,
            log_fn=lambda msg: None,
        )
        errors.extend(vendor_errors)

        normalized_questions: List[QuestionDraft] = []
        for pair in vendor_pairs:
            source_loc = pair.get("source_locator", "")
            
            # Grounding check: verify that source locator references an input chunk
            matched_chunk_id = None
            for c_id in chunk_id_map.keys():
                if c_id in source_loc:
                    matched_chunk_id = c_id
                    break

            # Fallback to first chunk if single chunk request, otherwise flag warning
            if not matched_chunk_id and len(req.chunks) == 1:
                matched_chunk_id = req.chunks[0].chunk_id

            warnings: List[str] = []
            if not matched_chunk_id:
                warnings.append("PROVENANCE_WARNING: LLM did not provide unambiguous chunk ID citation.")

            raw_bloom = pair.get("bloom_level", "UNDERSTAND").upper()
            valid_bloom = raw_bloom if raw_bloom in ("REMEMBER", "UNDERSTAND", "APPLY", "ANALYZE", "EVALUATE", "CREATE") else "UNDERSTAND"

            normalized_questions.append(
                QuestionDraft(
                    id=pair.get("id") or f"q-{uuid.uuid4().hex[:8]}",
                    question_text=pair.get("question", ""),
                    question_type=pair.get("question_type", "single_choice"),
                    options=pair.get("options", []),
                    suggested_answer=pair.get("ga_answer", ""),
                    marks=float(pair.get("score") or 1.0),
                    difficulty=pair.get("difficulty") or "medium",
                    bloom_level=valid_bloom,
                    bloom_verification_status="UNVERIFIED_BY_LECTURER",
                    source_locator=source_loc,
                    source_excerpt=pair.get("source_excerpt", ""),
                    provenance_chunk_id=matched_chunk_id,
                    status="DRAFT",
                    is_synthetic=False,
                    co_id=req.target_co_id,
                    topic_id=req.target_topic_ids[0] if req.target_topic_ids else None,
                    validation_warnings=warnings,
                )
            )

        return QuestionGenerationResponse(
            tenant_id=req.tenant_id,
            course_offering_id=req.course_offering_id,
            syllabus_version_id=req.syllabus_version_id,
            questions=normalized_questions,
            errors=errors,
            provider_info="vendor:exam_generator (DeepSeek/OpenAI)",
        )
    except Exception as e:
        logger.exception("Question generation error")
        # Sanitize error detail to never leak connection strings or keys
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="Question generation failed internally. Check service logs for details.",
        )
