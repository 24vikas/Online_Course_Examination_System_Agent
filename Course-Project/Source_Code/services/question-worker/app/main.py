def is_test_environment() -> bool:
    env = os.getenv("APP_ENV", "").lower()
    test_mode = os.getenv("TEST_MODE", "").lower()
    return env == "test" or test_mode in ("true", "1", "yes")

def get_service_secret() -> str:
    secret = os.getenv("QUESTION_WORKER_SECRET", "")
    if not secret or secret == "placeholder-question-worker-secret":
        if is_test_environment():
            return "test-internal-secret"
        # In production/staging, fail closed
        raise RuntimeError("CONFIGURATION_ERROR: QUESTION_WORKER_SECRET is not configured or using default placeholder.")
    return secret

def verify_internal_auth(
    x_service_key: Optional[str] = Header(None, alias="X-Internal-Service-Key"),
    authorization: Optional[str] = Header(None, alias="Authorization"),
):
    """Enforces server-to-server internal authentication with zero predictable defaults in production."""
    provided_key = x_service_key
    if not provided_key and authorization:
        parts = authorization.split(" ")
        if len(parts) == 2 and parts[0].lower() == "bearer":
            provided_key = parts[1]

    try:
        expected_secret = get_service_secret()
    except RuntimeError as e:
        logger.error(str(e))
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="Server service authentication is not properly configured.",
        )

    # Permit test key strictly in test mode
    if is_test_environment() and provided_key == "test-internal-secret":
        return True

    if not provided_key or provided_key != expected_secret:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Missing or invalid internal service authentication key",
        )
    return True


